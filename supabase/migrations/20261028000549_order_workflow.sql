-- Review and apply in the intended Supabase project after a backup.
-- The service role stays on the server; all public order access is revoked.
begin;
create extension if not exists pgcrypto;
create table if not exists public.permit_orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  company_name text, usdot text, mc_number text, vin text,
  plate_number text, phone_number text, permit_type text, permit_state text,
  processing_type text, total numeric, payment_status text, order_status text,
  order_items jsonb not null default '[]'::jsonb
);
alter table public.permit_orders
  add column if not exists order_number uuid default gen_random_uuid(),
  add column if not exists request_key uuid,
  add column if not exists request_fingerprint text,
  add column if not exists contact_email text,
  add column if not exists customer_details jsonb,
  add column if not exists quote jsonb,
  add column if not exists quote_revision uuid,
  add column if not exists approved_by uuid,
  add column if not exists approved_at timestamptz,
  add column if not exists stripe_session_id text,
  add column if not exists stripe_checkout_url text,
  add column if not exists stripe_payment_intent text,
  add column if not exists paid_at timestamptz,
  add column if not exists updated_at timestamptz default now(),
  add column if not exists last_updated_by uuid,
  add column if not exists permit_files jsonb,
  add column if not exists delivery_approved_at timestamptz,
  add column if not exists delivery_sent_at timestamptz;
create unique index if not exists permit_order_number_unique on public.permit_orders(order_number);
create unique index if not exists permit_request_key_unique on public.permit_orders(request_key);
create unique index if not exists permit_stripe_session_unique on public.permit_orders(stripe_session_id);
alter table public.permit_orders enable row level security;
revoke all on public.permit_orders from anon, authenticated;
grant all on public.permit_orders to service_role;

create table if not exists public.permit_mail_queue (
  id bigint generated always as identity primary key,
  message_key text not null unique,
  recipient text not null,
  subject text not null,
  html text not null,
  created_at timestamptz not null default now(),
  locked_until timestamptz,
  attempts integer not null default 0,
  sent_at timestamptz,
  provider_id text,
  last_error text
);
alter table public.permit_mail_queue enable row level security;
revoke all on public.permit_mail_queue from anon, authenticated;
grant all on public.permit_mail_queue to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.claim_permit_mail(batch_size integer default 15)
returns setof public.permit_mail_queue
language sql security invoker set search_path = public
as $$
  update public.permit_mail_queue q
  set locked_until = now() + interval '5 minutes', attempts = attempts + 1
  where q.id in (
    select id from public.permit_mail_queue
    where sent_at is null and (locked_until is null or locked_until < now())
    order by created_at for update skip locked limit least(greatest(batch_size, 1), 25)
  ) returning q.*;
$$;
revoke all on function public.claim_permit_mail(integer) from public, anon, authenticated;
grant execute on function public.claim_permit_mail(integer) to service_role;

-- Public request throttling is persisted across serverless instances.
create table if not exists public.permit_request_limits (
  key_hash text primary key, window_started timestamptz not null, request_count integer not null
);
alter table public.permit_request_limits enable row level security;
revoke all on public.permit_request_limits from anon, authenticated;
grant all on public.permit_request_limits to service_role;
create or replace function public.allow_permit_request(request_hash text)
returns boolean language plpgsql security invoker set search_path = public as $$
declare n integer;
begin
  insert into public.permit_request_limits(key_hash,window_started,request_count)
  values(request_hash,now(),1)
  on conflict(key_hash) do update set
    request_count = case when permit_request_limits.window_started < now()-interval '1 hour' then 1 else permit_request_limits.request_count+1 end,
    window_started = case when permit_request_limits.window_started < now()-interval '1 hour' then now() else permit_request_limits.window_started end
  returning request_count into n;
  return n <= 20;
end;
$$;
revoke all on function public.allow_permit_request(text) from public, anon, authenticated;
grant execute on function public.allow_permit_request(text) to service_role;

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('issued-permits','issued-permits',false,5242880,array['application/pdf'])
on conflict(id) do update set public=false,file_size_limit=5242880,allowed_mime_types=array['application/pdf'];

-- Queue delivery and save its evidence in the same transaction.
create or replace function public.queue_permit_delivery(
  p_order uuid, p_files jsonb, p_admin uuid, p_recipient text, p_subject text, p_html text
) returns boolean language plpgsql security invoker set search_path = public as $$
begin
  update public.permit_orders
    set order_status='delivery_queued', permit_files=p_files,
        last_updated_by=p_admin, delivery_approved_at=now()
    where order_number=p_order and order_status='issued' and payment_status='paid';
  if not found then raise exception 'Order is not ready for delivery'; end if;
  insert into public.permit_mail_queue(message_key,recipient,subject,html)
    values('delivery-'||p_order::text,p_recipient,p_subject,p_html);
  return true;
end;
$$;
revoke all on function public.queue_permit_delivery(uuid,jsonb,uuid,text,text,text) from public, anon, authenticated;
grant execute on function public.queue_permit_delivery(uuid,jsonb,uuid,text,text,text) to service_role;
commit;
